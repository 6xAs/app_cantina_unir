create table if not exists public.cantina_products (
 id bigint generated by default as identity primary key,
 name text not null check (char_length(name) between 2 and 120),
 description text not null default '',
 category text not null check (category in ('Salgados','Lanches','Bebidas','Doces')),
 price numeric(10,2) not null check (price >= 0),
 emoji text not null default '🍽️',
 available boolean not null default true,
 featured boolean not null default false,
 created_at timestamptz not null default now()
);
alter table public.cantina_products enable row level security;
revoke all on public.cantina_products from anon, authenticated;
grant select on public.cantina_products to anon, authenticated;
drop policy if exists "Cardapio publico somente leitura" on public.cantina_products;
create policy "Cardapio publico somente leitura" on public.cantina_products
 for select to anon,authenticated using (available = true);
